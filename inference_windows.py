@torch.no_grad()
def predict_image(net, img_path, conf_thresh=0.05, iou_thresh=0.45, device='cuda'):
    net.eval()

    img = Image.open(img_path).convert('RGB')
    orig_w, orig_h = img.size
    img_array = np.array(img)

    h, w = img_array.shape[:2]
    scale = min(512 / w, 512 / h)
    nw, nh = int(w * scale), int(h * scale)

    img_resized = Image.fromarray(img_array).resize((nw, nh), Image.BILINEAR)
    img_pad = Image.new('RGB', (512, 512), (114, 114, 114))
    img_pad.paste(img_resized, ((512 - nw) // 2, (512 - nh) // 2))

    x = torch.from_numpy(np.array(img_pad)).permute(2, 0, 1).unsqueeze(0).float() / 255.
    x = x.to(device)

    anchors, cls_preds, bbox_preds = net(x)

    anchors = anchors.to(device)              # [N,4]
    cls_preds = cls_preds[0]                  # [N,2]
    bbox_preds = bbox_preds[0]                # [N,4]

    scores = F.softmax(cls_preds, dim=1)[:, 1]

    boxes = decode_boxes(bbox_preds, anchors)
    boxes = boxes.clamp(0, 1)

    keep = scores > conf_thresh
    if keep.sum() == 0:
        return np.array([]), np.array([])

    boxes = boxes[keep]
    scores = scores[keep]

    keep = ops.nms(boxes, scores, iou_thresh)
    boxes = boxes[keep]
    scores = scores[keep]

    boxes = boxes.cpu().numpy()
    scores = scores.cpu().numpy()

    pad_x, pad_y = (512 - nw) / 2, (512 - nh) / 2
    boxes[:, [0, 2]] = (boxes[:, [0, 2]] * 512 - pad_x) / scale
    boxes[:, [1, 3]] = (boxes[:, [1, 3]] * 512 - pad_y) / scale

    boxes[:, [0, 2]] = np.clip(boxes[:, [0, 2]], 0, orig_w)
    boxes[:, [1, 3]] = np.clip(boxes[:, [1, 3]], 0, orig_h)

    return boxes, scores



def show_detections(img_path, boxes, scores, conf_thresh=0.5):
    """Показать результаты"""
    img = Image.open(img_path)
    fig, ax = plt.subplots(1, figsize=(12, 12))
    ax.imshow(img)

    for box, score in zip(boxes, scores):
        if score > conf_thresh:
            x1, y1, x2, y2 = box
            rect = patches.Rectangle((x1, y1), x2-x1, y2-y1,
                                   linewidth=2, edgecolor='red', facecolor='none')
            ax.add_patch(rect)
            ax.text(x1, y1-10, f'Face: {score:.3f}', color='red', fontsize=12,
                   bbox=dict(boxstyle="round,pad=0.3", facecolor="yellow", alpha=0.5))

    plt.axis('off')
    plt.show()

