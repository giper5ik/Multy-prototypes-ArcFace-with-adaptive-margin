def letterbox_fast(img_array):
    h, w = img_array.shape[:2]
    scale = min(512/w, 512/h)
    nw, nh = int(w*scale), int(h*scale)
    img_resized = np.array(Image.fromarray(img_array).resize((nw, nh), Image.BILINEAR))
    pad_img = np.full((512, 512, 3), 114, dtype=np.uint8)
    dx, dy = (512 - nw)//2, (512 - nh)//2
    pad_img[dy:dy+nh, dx:dx+nw] = img_resized
    return pad_img

def data_generator(batch_size=8):
    files = [item['img_name'] for item in label_cache]

    while True:
        np.random.shuffle(files)
        for i in range(0, len(files), batch_size):
            batch_X, batch_Y = [], []
            for j in range(min(batch_size, len(files)-i)):
                fname = files[i+j]
                cache_item = next(item for item in label_cache if item['img_name'] == fname)
                img = np.array(Image.open(os.path.join(BASE,fname)).convert('RGB'))
                img_norm = letterbox_fast(img)

                batch_X.append(img_norm)
                batch_Y.append(cache_item['boxes'])
            X = torch.tensor(np.array(batch_X), dtype=torch.float32).permute(0,3,1,2) / 255.0
            max_b = max(y.shape[0] for y in batch_Y) if batch_Y else 1
            Y = torch.zeros(len(batch_Y), max_b, 5) - 1
            for k, y in enumerate(batch_Y):
                if y.shape[0] > 0:
                    Y[k, :y.shape[0]] = torch.from_numpy(y)
            yield X.cuda(), Y.cuda()

