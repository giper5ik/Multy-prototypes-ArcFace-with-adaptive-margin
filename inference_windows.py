class MobileNet(nn.Module):
    def __init__(self):
        super().__init__()
        self.model = nn.Sequential(
            nn.Conv2d(3, 32, 3, 2, 1), nn.BatchNorm2d(32), nn.ReLU6(),
            nn.Conv2d(32, 32, 3, 1, 1, groups=32), nn.BatchNorm2d(32), nn.ReLU6(),
            nn.Conv2d(32, 64, 1), nn.BatchNorm2d(64), nn.ReLU6(),

            nn.Conv2d(64, 64, 3, 2, 1, groups=64), nn.BatchNorm2d(64), nn.ReLU6(),
            nn.Conv2d(64, 128, 1), nn.BatchNorm2d(128), nn.ReLU6(),

            nn.Conv2d(128, 128, 3, 2, 1, groups=128), nn.BatchNorm2d(128), nn.ReLU6(),
            nn.Conv2d(128, 256, 1), nn.BatchNorm2d(256), nn.ReLU6(),
        )

    def forward(self, x):
        return self.model(x)
class SSD(nn.Module):
    def __init__(self, num_classes=2):
        super().__init__()
        self.backbone = MobileNet()
        self.num_classes = num_classes

        self.sizes = [0.06, 0.1, 0.15]
        self.ratios = [0.5, 1.0, 1.5]
        self.num_anchors = len(self.sizes) * len(self.ratios)

        self.cls_head = nn.Conv2d(256, self.num_anchors * num_classes, 3, padding=1)
        self.box_head = nn.Conv2d(256, self.num_anchors * 4, 3, padding=1)

    def forward(self, x):
        feat = self.backbone(x)
        B, _, H, W = feat.shape

        cls = self.cls_head(feat)
        box = self.box_head(feat)

        cls = cls.permute(0,2,3,1).reshape(B, -1, self.num_classes)
        box = box.permute(0,2,3,1).reshape(B, -1, 4)

        anchors = self.generate_anchors(H, W, x.device)
        return anchors, cls, box

    def generate_anchors(self, H, W, device):
        ys, xs = torch.meshgrid(torch.arange(H), torch.arange(W), indexing="ij")
        xs = (xs + 0.5) / W
        ys = (ys + 0.5) / H

        anchors = []
        for s in self.sizes:
            for r in self.ratios:
                w = s * np.sqrt(r)
                h = s / np.sqrt(r)
                anchors.append(torch.stack([
                    xs - w/2, ys - h/2,
                    xs + w/2, ys + h/2
                ], dim=-1))
        anchors = torch.stack(anchors, dim=-2)
        return anchors.reshape(-1,4).clamp(0,1).to(device)

def encode_boxes(gt, anchors):
    ax = (anchors[:, 0] + anchors[:, 2]) / 2
    ay = (anchors[:, 1] + anchors[:, 3]) / 2
    aw = anchors[:, 2] - anchors[:, 0]
    ah = anchors[:, 3] - anchors[:, 1]

    gx = (gt[:, 0] + gt[:, 2]) / 2
    gy = (gt[:, 1] + gt[:, 3]) / 2
    gw = gt[:, 2] - gt[:, 0]
    gh = gt[:, 3] - gt[:, 1]

    dx = (gx - ax) / aw
    dy = (gy - ay) / ah
    dw = torch.log(gw / aw)
    dh = torch.log(gh / ah)

    return torch.stack([dx, dy, dw, dh], dim=1)
def decode_boxes(pred, anchors):
    ax = (anchors[:, 0] + anchors[:, 2]) / 2
    ay = (anchors[:, 1] + anchors[:, 3]) / 2
    aw = anchors[:, 2] - anchors[:, 0]
    ah = anchors[:, 3] - anchors[:, 1]

    gx = pred[:, 0] * aw + ax
    gy = pred[:, 1] * ah + ay
    gw = torch.exp(pred[:, 2]) * aw
    gh = torch.exp(pred[:, 3]) * ah

    return torch.stack([
        gx - gw/2, gy - gh/2,
        gx + gw/2, gy + gh/2
    ], dim=1)

def match_anchors(anchors, gt_boxes, iou_thresh=0.5):
    ious = ops.box_iou(anchors, gt_boxes)
    best_iou, best_gt = ious.max(dim=1)

    labels = torch.zeros(len(anchors), dtype=torch.long, device=anchors.device)
    labels[best_iou >= iou_thresh] = 1

    matched_gt = gt_boxes[best_gt]
    return labels, matched_gt

def ssd_loss(cls_pred, box_pred, anchors, gt_boxes, neg_ratio=3):
    if gt_boxes.numel() == 0:
        labels = torch.zeros(len(cls_pred), dtype=torch.long, device=cls_pred.device)
        return F.cross_entropy(cls_pred, labels)

    labels, matched_gt = match_anchors(anchors, gt_boxes)

    cls_loss_all = F.cross_entropy(cls_pred, labels, reduction="none")

    pos_mask = labels == 1
    neg_mask = labels == 0

    num_pos = pos_mask.sum()
    num_neg = min(neg_ratio * num_pos, neg_mask.sum())

    neg_loss = cls_loss_all[neg_mask]
    neg_topk, _ = torch.topk(neg_loss, k=num_neg)

    cls_loss = (
        cls_loss_all[pos_mask].sum() +
        neg_topk.sum()
    ) / (num_pos + num_neg + 1e-6)

    if num_pos > 0:
        box_tgt = encode_boxes(matched_gt[pos_mask], anchors[pos_mask])
        box_loss = F.smooth_l1_loss(box_pred[pos_mask], box_tgt)
    else:
        box_loss = torch.tensor(0., device=cls_pred.device)

    return cls_loss + 5 * box_loss

def train_one_epoch(net, loader, optimizer, device):
    net.train()
    total = 0

    for images, gt_boxes in loader:
        images = images.to(device)
        gt_boxes = gt_boxes.to(device)

        anchors, cls_pred, box_pred = net(images)

        loss = ssd_loss(
            cls_pred[0],
            box_pred[0],
            anchors,
            gt_boxes[0]
        )

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        total += loss.item()

    return total / len(loader)

