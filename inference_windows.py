def generate_anchors(H, W, sizes, device):
    ys, xs = torch.meshgrid(
        torch.arange(H), torch.arange(W), indexing="ij"
    )
    xs = (xs + 0.5) / W
    ys = (ys + 0.5) / H

    anchors = []
    for s in sizes:
        w = h = s
        anchors.append(torch.stack([
            xs - w/2,ys - h/2, xs + w/2,ys + h/2], dim=-1))

    anchors = torch.stack(anchors, dim=-2)
    return anchors.reshape(-1, 4).clamp(0, 1).to(device)

from torch.utils.data import Dataset

class FaceDataset(Dataset):
    def __init__(self, img_dir, annotations, img_size=512):
        self.img_dir = img_dir
        self.ann = annotations
        self.img_size = img_size

    def __len__(self):
        return len(self.ann)

    def letterbox(self, img):
        w, h = img.size
        s = min(self.img_size / w, self.img_size / h)
        nw, nh = int(w*s), int(h*s)

        img = img.resize((nw, nh), Image.BILINEAR)
        canvas = Image.new("RGB", (self.img_size, self.img_size), (114,114,114))
        dx, dy = (self.img_size-nw)//2, (self.img_size-nh)//2
        canvas.paste(img, (dx, dy))

        return canvas, s, dx, dy

    def __getitem__(self, idx):
        item = self.ann[idx]

        img = Image.open(os.path.join(self.img_dir, item["file"])).convert("RGB")
        img, scale, dx, dy = self.letterbox(img)

        img = torch.from_numpy(np.array(img)).permute(2,0,1).float() / 255.

        boxes = []
        for x0,y0,x1,y1 in item["boxes"]:
            x0 = (x0*scale + dx) / self.img_size
            y0 = (y0*scale + dy) / self.img_size
            x1 = (x1*scale + dx) / self.img_size
            y1 = (y1*scale + dy) / self.img_size
            boxes.append([x0,y0,x1,y1])

        boxes = torch.tensor(boxes, dtype=torch.float32)
        return img, boxes

